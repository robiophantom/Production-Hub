import type { Metadata } from "next";
import Link from "next/link";
import {
  AlertOctagon,
  BellRing,
  CheckCircle2,
  Clock3,
  Search,
  ShieldCheck,
} from "lucide-react";
import { ConfirmAction } from "@/components/ui/confirm-action";
import { HealthBadge, StatusBadge, Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { EmptyState, InfoNote } from "@/components/ui/feedback";
import { Input } from "@/components/ui/form";
import { PageHeader } from "@/components/ui/page-header";
import { StatCard } from "@/components/ui/stat-card";
import { requireRoles } from "@/lib/auth/session";
import { ALERT_WINDOWS, ALERT_WINDOW_LABELS } from "@/lib/constants";
import { canPlanOrders } from "@/lib/services/access";
import {
  getAlertStats,
  getAlerts,
  scanDelayAlerts,
  type AlertFilters,
  type AlertView,
} from "@/lib/services/alerts";
import { formatDate, formatDateTime, formatNumber } from "@/lib/utils";
import { confirmAlertAction, dismissAlertAction } from "./actions";
import { ScanButton } from "./scan-button";

export const metadata: Metadata = { title: "Delay alerts" };

const STATUS_TABS = [
  { id: "active", label: "Active" },
  { id: "open", label: "Awaiting review" },
  { id: "confirmed", label: "Confirmed" },
  { id: "dismissed", label: "Dismissed" },
  { id: "resolved", label: "Resolved" },
  { id: "all", label: "All" },
] as const;

type StatusTab = (typeof STATUS_TABS)[number]["id"];

function readStatus(value: string | string[] | undefined): StatusTab {
  const raw = Array.isArray(value) ? value[0] : value;
  return STATUS_TABS.some((tab) => tab.id === raw) ? (raw as StatusTab) : "active";
}

function readWindow(value: string | string[] | undefined): AlertFilters["window"] | undefined {
  const raw = Array.isArray(value) ? value[0] : value;
  return ALERT_WINDOWS.includes(raw as (typeof ALERT_WINDOWS)[number])
    ? (raw as AlertFilters["window"])
    : undefined;
}

function readRisk(value: string | string[] | undefined): AlertFilters["risk"] | undefined {
  const raw = Array.isArray(value) ? value[0] : value;
  return raw === "red" || raw === "amber" ? raw : undefined;
}

export default async function AlertsPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const user = await requireRoles("super_admin", "managing_director", "merchandiser");
  const query = await searchParams;
  const status = readStatus(query.status);
  const window = readWindow(query.window);
  const risk = readRisk(query.risk);
  const search = typeof query.search === "string" ? query.search : "";
  const managed = canPlanOrders(user.role);

  let scanMessage: string | null = null;
  try {
    const scan = await scanDelayAlerts(user);
    if (scan.created > 0 || scan.resolved > 0 || scan.updated > 0) {
      scanMessage = `Delay engine refreshed: ${scan.created} new alert(s), ${scan.updated} updated, ${scan.resolved} resolved. The scan uses reported output and the working-day calendar — not AI.`;
    }
  } catch (error) {
    console.error("[alerts] scan failed", error);
  }

  const [alerts, stats] = await Promise.all([
    getAlerts(user, { status, window, risk, search }),
    getAlertStats(user),
  ]);

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Delay control"
        title="Delay alerts"
        description="Alerts are generated by the deterministic delay engine at the 14, 7 and 3 working-day windows, plus overdue. A buyer-facing notification is created only when a merchandiser explicitly confirms an alert."
        actions={<ScanButton />}
      />

      {scanMessage ? <InfoNote variant="info">{scanMessage}</InfoNote> : null}

      <section className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <StatCard
          label="Active alerts"
          value={formatNumber(stats.active)}
          icon={BellRing}
          tone="brand"
          hint="Open or confirmed delay risks"
        />
        <StatCard
          label="Awaiting review"
          value={formatNumber(stats.open)}
          icon={Clock3}
          tone="amber"
          hint="Confirm or dismiss before buyers can be notified"
        />
        <StatCard
          label="Overdue milestones"
          value={formatNumber(stats.overdue)}
          icon={AlertOctagon}
          tone="red"
          hint="Planned date passed with quantity remaining"
        />
        <StatCard
          label="Confirmed"
          value={formatNumber(stats.confirmed)}
          icon={ShieldCheck}
          tone="green"
          hint="Reviewed and published to the buyer portal"
        />
      </section>

      {!managed ? (
        <InfoNote variant="info" title="Read-only review">
          Managing Director access is view-only for alert confirmation. A Super Admin or the assigned
          merchandiser must confirm or dismiss alerts.
        </InfoNote>
      ) : null}

      <div className="flex flex-col gap-3 border-b border-line pb-1 lg:flex-row lg:items-center lg:justify-between">
        <nav className="scrollbar-thin -mb-px flex gap-1 overflow-x-auto">
          {STATUS_TABS.map((tab) => {
            const active = tab.id === status;
            const params = new URLSearchParams();
            if (tab.id !== "active") params.set("status", tab.id);
            if (window) params.set("window", window);
            if (risk) params.set("risk", risk);
            if (search) params.set("search", search);
            const qs = params.toString();
            const href = qs ? `/alerts?${qs}` : "/alerts";
            return (
              <Link
                key={tab.id}
                href={href}
                aria-current={active ? "page" : undefined}
                className={
                  active
                    ? "relative whitespace-nowrap rounded-t-md px-3 py-2.5 text-[13px] font-semibold text-brand after:absolute after:inset-x-2 after:-bottom-px after:h-0.5 after:rounded-full after:bg-brand"
                    : "whitespace-nowrap rounded-t-md px-3 py-2.5 text-[13px] font-medium text-muted hover:text-ink"
                }
              >
                {tab.label}
              </Link>
            );
          })}
        </nav>

        <form action="/alerts" className="flex items-center gap-2">
          {status !== "active" ? <input type="hidden" name="status" value={status} /> : null}
          {window ? <input type="hidden" name="window" value={window} /> : null}
          {risk ? <input type="hidden" name="risk" value={risk} /> : null}
          <div className="relative">
            <Search className="pointer-events-none absolute left-3 top-1/2 size-4 -translate-y-1/2 text-slate-400" />
            <Input
              name="search"
              defaultValue={search}
              placeholder="Search PO, style, buyer or stage"
              className="h-9 w-full pl-9 sm:w-64"
            />
          </div>
          <Button type="submit" variant="outline" size="sm">
            Search
          </Button>
        </form>
      </div>

      {alerts.length === 0 ? (
        <EmptyState
          icon={CheckCircle2}
          title={status === "active" ? "No active delay alerts" : "No alerts in this view"}
          description={
            status === "active"
              ? "Every active milestone in your scope is either healthy, complete, or outside the 14-day alert window. Run a scan after the next production submissions."
              : "Try a different status, risk level or search term."
          }
        />
      ) : (
        <div className="space-y-4">
          {alerts.map((alert) => (
            <AlertCard key={alert.id} alert={alert} managed={managed} />
          ))}
        </div>
      )}
    </div>
  );
}

function AlertCard({ alert, managed }: { alert: AlertView; managed: boolean }) {
  const formula = Array.isArray(alert.calculation?.formula)
    ? (alert.calculation.formula as string[])
    : [];
  const open = alert.status === "open";

  return (
    <Card className={alert.risk_level === "red" ? "border-l-4 border-l-red-500" : "border-l-4 border-l-amber-400"}>
      <CardHeader className="flex-row flex-wrap items-start justify-between gap-3">
        <div className="min-w-0">
          <div className="flex flex-wrap items-center gap-2">
            <HealthBadge health={alert.risk_level} />
            <Badge variant={alert.warning_window === "overdue" ? "danger" : "warning"}>
              {ALERT_WINDOW_LABELS[alert.warning_window]}
            </Badge>
            <StatusBadge status={alert.status} />
            {alert.buyer_notified ? (
              <Badge variant="success">
                <CheckCircle2 className="size-3" /> Buyer update published
              </Badge>
            ) : null}
          </div>
          <CardTitle className="mt-2 text-[15px]">
            <Link href={`/orders/${alert.po_id}?tab=delay`} className="hover:text-brand">
              {alert.po_number}
            </Link>
            <span className="ml-2 font-normal text-slate-500">{alert.stage_name}</span>
          </CardTitle>
          <CardDescription>
            {alert.buyer_name} ({alert.buyer_code}) · {alert.style_name} · Ex-factory{" "}
            {formatDate(alert.ex_factory_date)} · Stage planned {formatDate(alert.planned_date)}
          </CardDescription>
        </div>

        {managed && open ? (
          <div className="flex flex-wrap items-center gap-2">
            <ConfirmAction
              action={confirmAlertAction}
              hidden={{ alertId: alert.id }}
              title="Confirm delay and notify the buyer?"
              description="This approves a buyer-facing status update using the deterministic delay calculation shown below. Only your explicit confirmation publishes it to the buyer portal."
              confirmLabel="Confirm & notify buyer"
              triggerLabel="Confirm & notify"
              icon={<BellRing />}
            />
            <ConfirmAction
              action={dismissAlertAction}
              hidden={{ alertId: alert.id }}
              title="Dismiss this alert"
              description="Dismissing records your reason. The same warning window will not be raised again for this milestone unless the risk later escalates."
              confirmLabel="Dismiss alert"
              triggerLabel="Dismiss"
              variant="outline"
              prompt={{
                name: "reason",
                label: "Dismissal reason",
                placeholder: "Explain why this alert is not a genuine risk…",
                required: true,
              }}
            />
          </div>
        ) : null}
      </CardHeader>

      <CardContent className="space-y-4">
        <dl className="grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-6">
          <Metric label="Remaining" value={`${formatNumber(alert.remaining_qty)} pcs`} />
          <Metric label="Working days left" value={String(alert.working_days_left)} />
          <Metric label="Required / day" value={`${alert.required_daily.toFixed(1)} pcs`} />
          <Metric
            label="Actual / day"
            value={`${alert.actual_daily.toFixed(1)} pcs`}
            warn={alert.actual_daily < alert.required_daily}
          />
          <Metric label="Projected completion" value={formatDate(alert.projected_completion_date)} />
          <Metric label="Daily shortfall" value={`${alert.shortfall.toFixed(1)} pcs`} warn={alert.shortfall > 0} />
        </dl>

        {formula.length > 0 ? (
          <details className="rounded-lg border border-line bg-slate-50/70 px-3 py-2">
            <summary className="cursor-pointer text-[12px] font-semibold text-slate-600">
              Why this alert fired — transparent calculation
            </summary>
            <ul className="mt-2 space-y-1 text-[12px] leading-relaxed text-slate-600">
              {formula.map((line, index) => (
                <li key={index} className="tabular-nums">
                  {line}
                </li>
              ))}
            </ul>
          </details>
        ) : null}

        <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-[11px] text-muted">
          <span>Alert date: {formatDate(alert.alert_date)}</span>
          {alert.confirmed_by_name ? (
            <span>
              Reviewed by {alert.confirmed_by_name} · {formatDateTime(alert.confirmed_at)}
            </span>
          ) : (
            <span>Not reviewed yet</span>
          )}
          {alert.notification_id ? (
            <span>
              Buyer notification {alert.notification_status ?? "approved"}
              {alert.notification_sent_at ? ` · sent ${formatDateTime(alert.notification_sent_at)}` : ""}
            </span>
          ) : null}
          {alert.dismiss_reason ? <span>Reason: {alert.dismiss_reason}</span> : null}
        </div>
      </CardContent>
    </Card>
  );
}

function Metric({ label, value, warn }: { label: string; value: string; warn?: boolean }) {
  return (
    <div>
      <dt className="text-[11px] text-muted">{label}</dt>
      <dd
        className={
          warn
            ? "mt-0.5 text-[13px] font-semibold tabular-nums text-amber-700"
            : "mt-0.5 text-[13px] font-semibold tabular-nums text-ink"
        }
      >
        {value}
      </dd>
    </div>
  );
}
